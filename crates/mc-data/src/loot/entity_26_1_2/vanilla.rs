use std::path::Path;

use super::{CompiledEntityLootTable, EntityLootCatalog};
use crate::Identifier;

/// Load the Java 26.1.2 entity tables, compiled with their reference closure,
/// from the startup-selected vanilla content root.
///
/// # Errors
///
/// Returns the exact missing, unreadable or invalid table.
pub fn load_vanilla(root: &Path) -> Result<EntityLootCatalog, String> {
    let mut roots = Vec::new();
    let mut tables = Vec::with_capacity(RESOURCES.len());
    for &(name, relative) in RESOURCES {
        let id =
            Identifier::parse(name).map_err(|error| format!("loot identifier {name}: {error}"))?;
        if name.starts_with("minecraft:entities/") {
            roots.push(id.clone());
        }
        let source = crate::runtime_resources::read_json(root, relative)?;
        tables.push(
            CompiledEntityLootTable::compile(id, &source).map_err(|error| {
                format!(
                    "compiling entity loot {}: {error}",
                    root.join(relative).display()
                )
            })?,
        );
    }
    EntityLootCatalog::from_tables(roots, tables)
        .map_err(|error| format!("entity loot closure under {}: {error}", root.display()))
}

