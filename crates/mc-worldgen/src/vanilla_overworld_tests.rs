//! Observed 26.1.2 fixtures from the headless vanilla RandomState/chunk generator.
use crate::{TerrainGenerator, vanilla_climate::VanillaClimate};
use mc_data::Identifier;
use mc_world::{BlockRegistry, ChunkGenerator, ChunkPos};
use std::{path::PathBuf, sync::Arc};

fn content_cache() -> Option<PathBuf> {
    let root = std::env::var_os("SOLARIS_CONTENT_CACHE")
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../data/vanilla"));
    if root
        .join("data/minecraft/worldgen/noise_settings/overworld.json")
        .is_file()
    {
        Some(root)
    } else {
        eprintln!(
            "SKIP vanilla overworld fixtures: export local bootstrap worldgen data with tools/extract-vanilla-worldgen.sh"
        );
        None
    }
}

#[test]
fn vanilla_three_seed_climate_and_height_fixtures() {
    let Some(root) = content_cache() else { return };
    let blocks = Arc::new(
        BlockRegistry::from_report(&mc_data::blocks::solaris_required_blocks_report()).unwrap(),
    );
    // Fixtures are independently observed native results, not values generated by Solaris.
    for (seed, fixtures) in [
        (
            0,
            [
                (0, 0, 55, "river", [1182, -13, -81, -1039, -881, 111]),
                (-128, 128, 60, "forest", [1190, -186, -35, -513, -82, 1279]),
                (
                    2048,
                    -2048,
                    66,
                    "savanna",
                    [4168, -2854, 967, 2334, 227, -4437],
                ),
            ],
        ),
        (
            81,
            [
                (
                    0,
                    0,
                    49,
                    "cold_ocean",
                    [-3210, -1132, -3768, -4529, -1237, -4628],
                ),
                (
                    -128,
                    128,
                    47,
                    "cold_ocean",
                    [-3665, -3203, -3174, -2879, -1237, -407],
                ),
                (
                    2048,
                    -2048,
                    66,
                    "savanna",
                    [3100, -1708, 4824, 2220, 16, 1263],
                ),
            ],
        ),
        (
            497625,
            [
                (
                    0,
                    0,
                    72,
                    "birch_forest",
                    [1141, 1339, -1500, -978, 582, -5630],
                ),
                (
                    -128,
                    128,
                    97,
                    "birch_forest",
                    [995, 1320, 1024, -897, 2773, -6706],
                ),
                (
                    2048,
                    -2048,
                    65,
                    "dark_forest",
                    [740, 4427, 1083, 570, 67, 2964],
                ),
            ],
        ),
    ] {
        let climate = VanillaClimate::new(seed as u64, &root).unwrap();
        let mut terrain = TerrainGenerator::new(seed, blocks.clone());
        terrain.load_vanilla_worldgen(&root).unwrap();
        for (x, z, height, biome, target) in fixtures {
            let sample = climate.sample(x, 64, z);
            assert_eq!(sample.quantized, target, "seed {seed}, ({x},64,{z})");
            assert_eq!(
                sample.biome,
                format!("minecraft:{biome}"),
                "seed {seed}, ({x},64,{z})"
            );
            assert_eq!(
                terrain.surface_height(x, z),
                height,
                "seed {seed}, ({x},{z})"
            );
            assert_eq!(terrain.noise_biome(x, 64, z).as_str(), sample.biome);
        }
    }
}

#[test]
fn vanilla_density_height_and_ocean_water_reach_generated_blocks() {
    let Some(root) = content_cache() else { return };
    let blocks = Arc::new(
        BlockRegistry::from_report(&mc_data::blocks::solaris_required_blocks_report()).unwrap(),
    );
    let water = blocks
        .block(&Identifier::parse("minecraft:water").unwrap())
        .unwrap()
        .default;
    let air = blocks
        .block(&Identifier::parse("minecraft:air").unwrap())
        .unwrap()
        .default;
    let mut terrain = TerrainGenerator::new(81, blocks);
    terrain.load_vanilla_worldgen(&root).unwrap();
    let chunk = terrain.generate(ChunkPos { x: 0, z: 0 });
    let top = 49; // Native OCEAN_FLOOR_WG top at seed81 block(0,0).
    assert_ne!(chunk.get_block(0, top, 0), Some(air));
    assert_eq!(chunk.get_block(0, top + 1, 0), Some(water));
    assert_eq!(chunk.get_block(0, 62, 0), Some(water));
    assert_eq!(chunk.get_block(0, 63, 0), Some(air));
}

#[test]
fn vanilla_chunk_density_matches_columns_at_cells_and_negative_borders() {
    let Some(root) = content_cache() else { return };
    for seed in [0, 81, 497625] {
        let density = crate::vanilla_density::VanillaDensity::new(seed, &root).unwrap();
        let mut chunk = vec![0.0; density.height() as usize * 256];
        let mut column = vec![0.0; density.height() as usize];
        // The unaligned square crosses six lattice points on each axis, rather
        // than the usual five. Each column independently evaluates its corners.
        for (min_x, min_z) in [(0, 0), (-16, -16), (192, -448), (-7, 5)] {
            density.fill_density_chunk(min_x, min_z, &mut chunk);
            for z in 0..16 {
                for x in 0..16 {
                    density.fill_density_column(min_x + x, min_z + z, &mut column);
                    for (y, expected) in column.iter().enumerate() {
                        assert_eq!(
                            chunk[y * 256 + z as usize * 16 + x as usize].to_bits(),
                            expected.to_bits(),
                            "seed {seed}, ({},{},{})",
                            min_x + x,
                            density.min_y() + y as i32,
                            min_z + z,
                        );
                    }
                }
            }
        }
    }
}

#[test]
fn vanilla_halo_surface_heights_match_independent_queries() {
    let Some(root) = content_cache() else { return };
    for seed in [0, 81, 497625] {
        let density = crate::vanilla_density::VanillaDensity::new(seed, &root).unwrap();
        let mut sampler = density.surface_height_sampler(-25, -9, 8, 24);
        // Reverse alternating rows to exercise reuse across cells and negative
        // quart boundaries, independently of the generator's visitation order.
        for z in -9..=24 {
            for offset in 0..34 {
                let x = if z % 2 == 0 { -25 + offset } else { 8 - offset };
                assert_eq!(
                    sampler.surface_height(x, z),
                    density.surface_height(x, z),
                    "seed {seed}, ({x},{z})",
                );
            }
        }
        // A bounded cache miss must remain an exact query, not clamp a column.
        for (x, z) in [(-129, 128), (192, -448), (-25, -9), (8, 24)] {
            assert_eq!(
                sampler.surface_height(x, z),
                density.surface_height(x, z),
                "seed {seed}, ({x},{z}) after halo",
            );
        }
    }
}
